// Writes src/*.ts, the token sets, from upstream data: npm packages (devDependencies) and files fetched at a pinned commit.
// Run: bun run generate (this script, then vp fmt src).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname } from "node:path";

import * as radix from "@radix-ui/colors";
import * as opColors from "open-props/src/colors";
import opBorders from "open-props/src/borders";
import opEasing from "open-props/src/easing";
import opFonts from "open-props/src/fonts";
import opShadows from "open-props/src/shadows";
import opSizes from "open-props/src/sizes";

const EASINGS_NET = "d2563f0d32a511b5556774b838ec35c3a841b15d";
const FLEXOKI = "8d723bac4a9ac46adfdf99d42155286977aac72a";

const require = createRequire(import.meta.url);
const src = `${import.meta.dirname}/../src`;
const version = (pkg: string) =>
  (JSON.parse(readFileSync(require.resolve(`${pkg}/package.json`), "utf8")) as { version: string })
    .version;
const fetchText = async (url: string) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
};

type Json = string | number | { readonly [key: string]: Json };
type Group = Record<string, Json>;
const leaves = (type: string, entries: [string, string | number][]) => ({
  $type: type,
  ...Object.fromEntries(entries.map(([k, v]) => [k, { $value: v }])),
});
const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const tidy = (v: string) => v.replace(/\s+/g, " ").replace(/\( /g, "(").replace(/ \)/g, ")").trim();
// open-props states some sizes in rem, which an @property initial value cannot hold: 16px to the rem.
const px = (v: string) => v.replace(/(-?[\d.]+)rem\b/g, (_, n: string) => `${Number(n) * 16}px`);
// The entries of a `--prefix-key: value` record whose key is a plain step (no `-fluid-`, `-content-` ...), prefix removed.
const steps = (props: Record<string, string>, prefix: string, key = /^[\w]+$/) =>
  Object.entries(props).flatMap(([name, v]) => {
    const k = name.slice(prefix.length);
    return name.startsWith(prefix) && key.test(k) ? [[k, v] as [string, string]] : [];
  });
// JSON with `$type` first (an integer-like key such as "1" would otherwise come before it).
const print: (v: Json) => string = (v) => {
  if (typeof v !== "object") return JSON.stringify(v);
  const entries = Object.entries(v).sort(
    ([a], [b]) => Number(b === "$type") - Number(a === "$type"),
  );
  return `{${entries.map(([k, x]) => `${JSON.stringify(k)}:${print(x)}`).join(",")}}`;
};
const write = (file: string, header: string, exports: Group) => {
  const body = Object.entries(exports)
    .map(([name, value]) => `export const ${name} = ${print(value)} as const;\n`)
    .join("\n");
  writeFileSync(
    `${src}/${file}`,
    `// Generated by scripts/generate.ts ${header}: do not edit.\n${body}`,
  );
};

// ---------- open-props
{
  const colors = Object.fromEntries(
    Object.entries(opColors)
      .filter(([name]) => name !== "default")
      .map(([name, props]) => {
        const hue = name.toLowerCase();
        return [hue, leaves("color", steps(props, `--${hue}-`, /^\d+$/))];
      }),
  );
  const sizes = leaves("dimension", [
    ...steps(opSizes, "--size-px-"),
    ...steps(opSizes, "--size-", /^(x*s|sm|md|lg|x*l)$/),
  ]);
  const radii = leaves(
    "dimension",
    steps(opBorders, "--radius-", /^(\d+|round)$/).map(([k, v]) => [k, px(v)]),
  );
  const borderSizes = leaves("dimension", steps(opBorders, "--border-size-"));
  const fontWeights = leaves(
    "fontWeight",
    steps(opFonts, "--font-weight-").map(([k, v]) => [k, Number(v)]),
  );
  const lineHeights = leaves(
    "number",
    steps(opFonts, "--font-lineheight-").map(([k, v]) => [k, Number(v)]),
  );
  // No token type holds a timing function or a shadow: these are CSS strings (README, "Limits").
  const ease = opEasing as Record<string, string>;
  // an alias (`--ease-elastic-1: var(--ease-elastic-out-1)`) is its target, a literal
  const resolve = (v: string) =>
    tidy(v.replace(/^var\((--[\w-]+)\)$/, (_, ref: string) => ease[ref]));
  const easings = Object.fromEntries(
    Object.entries(ease).map(([name, v]) => [camel(name.slice(2)), resolve(v)]),
  );
  // The shadows read --shadow-color and --shadow-strength(-N); they are resolved here, light and dark.
  const shadowSet = (dark: boolean) => {
    const props = opShadows as Record<string, string>;
    const pick = (name: string) => props[dark ? `${name}-@media:dark` : name];
    const strength = Number.parseFloat(pick("--shadow-strength"));
    const value = (ref: string) => {
      if (ref === "--shadow-color") return pick(ref);
      if (ref === "--shadow-strength") return `${strength}%`;
      const add = /calc\(var\(--shadow-strength\) \+ (\d+)%\)/.exec(props[ref] ?? "");
      if (add) return `${strength + Number(add[1])}%`;
      if (ref === "--inner-shadow-highlight") return pick(ref);
      throw new Error(`open-props shadow: ${ref}`);
    };
    return Object.fromEntries(
      Object.entries(props)
        .filter(([name]) => /^--(inner-)?shadow-\d+$/.test(name))
        .map(([name, v]) => [
          camel(name.slice(2)),
          tidy(v.replace(/var\((--[\w-]+)\)/g, (_, ref: string) => value(ref))),
        ]),
    );
  };
  write("open-props.ts", `from open-props ${version("open-props")}`, {
    colors,
    sizes,
    radii,
    borderSizes,
    fontWeights,
    lineHeights,
    easings,
    shadows: shadowSet(false),
    shadowsDark: shadowSet(true),
  });
}

// ---------- easings.net
{
  const yml = await fetchText(
    `https://raw.githubusercontent.com/ai/easings.net/${EASINGS_NET}/src/easings.yml`,
  );
  const easings = Object.fromEntries(
    [...yml.matchAll(/^- name: (\w+)\n\s+css:\s+(cubic-bezier\([^)]*\))/gm)].map((m) => [
      m[1],
      m[2],
    ]),
  );
  write("easings.ts", `from easings.net (ai/easings.net@${EASINGS_NET.slice(0, 7)})`, { easings });
}

// ---------- Radix colors
{
  const r = radix as unknown as Record<string, Record<string, string>>;
  const scales = Object.keys(r).filter(
    (k) => /^[a-z]+$/.test(k) && k !== "default" && r[`${k}Dark`],
  );
  // `blue1` .. `blue12` (or `blueA1`) to the step
  const stepsOf = (scale: Record<string, string>) =>
    Object.entries(scale).map(([k, v]) => [/\d+$/.exec(k)![0], v] as [string, string]);
  // Solid and alpha scales are separate sets: all of them in one createTokens() call is over TypeScript's instantiation limit.
  const light: Group = {};
  const lightAlpha: Group = {};
  const dark: Group = {};
  const darkAlpha: Group = {};
  const overrides = (scale: Record<string, string>) =>
    Object.fromEntries(stepsOf(scale).map(([k, v]) => [`_${k}`, v]));
  for (const s of scales) {
    light[s] = leaves("color", stepsOf(r[s]));
    lightAlpha[`${s}A`] = leaves("color", stepsOf(r[`${s}A`]));
    dark[s] = overrides(r[`${s}Dark`]);
    darkAlpha[`${s}A`] = overrides(r[`${s}DarkA`]);
  }
  for (const s of ["blackA", "whiteA"]) lightAlpha[s] = leaves("color", stepsOf(r[s]));
  write("radix.ts", `from @radix-ui/colors ${version("@radix-ui/colors")}`, {
    light,
    dark,
    lightAlpha,
    darkAlpha,
  });
}

// ---------- Flexoki
{
  const css = await fetchText(
    `https://raw.githubusercontent.com/kepano/flexoki/${FLEXOKI}/css/flexoki.css`,
  );
  const groups: Record<string, [string, string][]> = {};
  for (const [, name, value] of css.matchAll(/--flexoki-([\w-]+):\s*(#[0-9A-Fa-f]+);/g)) {
    const m = /^(?:([a-z]+)-)?(\w+)$/.exec(name)!;
    (groups[m[1] ?? "base"] ??= []).push([m[2], value.toLowerCase()]);
  }
  const flexoki = Object.fromEntries(
    Object.entries(groups).map(([g, entries]) => [g, leaves("color", entries)]),
  );
  write("flexoki.ts", `from Flexoki (kepano/flexoki@${FLEXOKI.slice(0, 7)})`, { flexoki });
}

// ---------- Reasonable Colors
{
  const dir = dirname(require.resolve("reasonable-colors/package.json"));
  const css = readFileSync(`${dir}/reasonable-colors.css`, "utf8");
  const groups: Record<string, [string, string][]> = {};
  for (const [, hue, step, value] of css.matchAll(/--color-([a-z]+)-(\d+):\s*(#[0-9a-f]+);/gi))
    (groups[hue] ??= []).push([step, value.toLowerCase()]);
  const reasonableColors = Object.fromEntries(
    Object.entries(groups).map(([g, entries]) => [g, leaves("color", entries)]),
  );
  write("reasonable-colors.ts", `from reasonable-colors ${version("reasonable-colors")}`, {
    reasonableColors,
  });
}
