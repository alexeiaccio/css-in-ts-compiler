// Writes src/groups/<id>.ts, one module per Baseline group of cssints (`@cssints/reset/<id>`), from the group data of
// cssints (the spec groups are not variants). not-discouraged bans three properties and four keywords that the reset has
// none of: it would be the full reset again (test/reset.mjs checks that it stays so). Run: bun run variants
import { mkdirSync, rmSync, writeFileSync } from "node:fs";

import { groups } from "../../cssints/src/groups-data.ts";

const ids = [
  "limited-availability",
  ...Object.entries(groups).flatMap(([id, g]) =>
    g.kind === "baseline" && id !== "not-discouraged" ? [id] : [],
  ),
];
const out = `${import.meta.dirname}/../src/groups`;
rmSync(out, { recursive: true, force: true });
for (const id of ids) {
  const up = "../".repeat(id.split("/").length);
  mkdirSync(`${out}/${id}`.replace(/\/[^/]*$/, ""), { recursive: true });
  writeFileSync(
    `${out}/${id}.ts`,
    `// Generated by scripts/variants.ts. Do not edit.
import { make, type Reset } from "${up}make.ts";

/** \`reset({ media?, prose? })\` with the declarations of cssints/${id} only (the README has what it drops). */
export const reset: Reset = make(${JSON.stringify(id)});
`,
  );
}
console.log(`variants: ${ids.length}`);
