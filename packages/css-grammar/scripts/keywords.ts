// Writes src/keywords.ts: the keywords of every property's grammar (and of the <types> it uses, each once), which
// the types offer as completions inside a string that is not a value yet. Run after `bun run extract`.
import { writeFileSync } from "node:fs";

import { properties, syntaxes } from "../src/mdn.ts";
import type { Node } from "../src/twin-core.ts";
import { parseGrammar } from "../src/twin-core.ts";

const props: Record<string, string> = properties;
const syns: Record<string, string> = syntaxes;

type Acc = { kws: Set<string>; types: Set<string> };
// Keywords of a node; a <type> is either followed (`flat`) or recorded by name, a <'property'> is always followed.
const walk = (n: Node, acc: Acc, flat: boolean, seen: Set<string>) => {
  switch (n[0]) {
    case "kw":
      acc.kws.add(n[1]);
      return;
    case "type": {
      const g = syns[n[1]];
      if (g === undefined || n[1].endsWith("()")) return;
      if (!flat) return void acc.types.add(n[1]);
      if (seen.has(n[1])) return;
      seen.add(n[1]);
      return walk(parseGrammar(g), acc, flat, seen);
    }
    case "prop": {
      const g = props[n[1]];
      if (g === undefined || seen.has(`'${n[1]}`)) return;
      seen.add(`'${n[1]}`);
      return walk(parseGrammar(g), acc, flat, seen);
    }
    case "fn":
    case "opt":
    case "star":
    case "plus":
    case "list":
    case "bang":
    case "rep":
      return walk(n[n[0] === "fn" ? 2 : 1] as Node, acc, flat, seen);
    case "alt":
    case "or":
    case "and":
    case "seq":
      for (const x of n[1]) walk(x, acc, flat, seen);
  }
};

const lit = (s: string) => JSON.stringify(s);
const alias = (t: string) => `K_${t.replace(/[^a-z0-9]/gi, "_")}`;
const perProp = Object.keys(props).map((p) => {
  const acc: Acc = { kws: new Set(), types: new Set() };
  walk(parseGrammar(props[p]!), acc, false, new Set([`'${p}`]));
  return [p, acc] as const;
});
const used = new Set(perProp.flatMap(([, a]) => [...a.types]));
const aliases = [...used].sort().flatMap((t) => {
  const acc: Acc = { kws: new Set(), types: new Set() };
  walk(parseGrammar(syns[t]!), acc, true, new Set([t]));
  return acc.kws.size ? [`type ${alias(t)} = ${[...acc.kws].sort().map(lit).join(" | ")};`] : [];
});
const have = new Set(aliases.map((a) => a.split(" ")[1]));
const lines = perProp.flatMap(([p, a]) => {
  const parts = [
    ...[...a.kws].sort().map(lit),
    ...[...a.types].sort().map(alias).filter((x) => have.has(x)),
  ];
  return parts.length ? [`  ${lit(p)}: ${parts.join(" | ")};`] : [];
});
writeFileSync(
  new URL("../src/keywords.ts", import.meta.url),
  `// generated by scripts/keywords.ts from mdn.ts: the keywords a property's grammar has, for completions (css.ts Hint)\n${aliases.join("\n")}\nexport interface Keywords {\n${lines.join("\n")}\n}\n`,
);
