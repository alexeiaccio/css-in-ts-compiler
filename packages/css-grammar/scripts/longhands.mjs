// Writes src/longhands.ts: the longhands of every shorthand, as Chrome expands it (set the shorthand to `initial` on an
// element and read the longhands its style lists). The sheet orders shorthand before longhand by these counts, and cn()
// tells containment from overlap by these sets. mdn-data `computed` was wrong here (`all` had one leaf, logical border
// sides listed physical shorthands, `font-variant` had none: docs/research/sublayers.md). A property Chrome does not
// know falls back to mdn-data `computed`. Run after a Chrome or mdn-data bump: `bun run longhands` (needs an installed
// Chrome, through playwright-core, channel "chrome").
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

import { chromium } from "playwright-core";

import { properties } from "../src/mdn.ts";

const MDN = createRequire(import.meta.url)("mdn-data/css/properties.json");
const leaves = (p) => {
  const c = MDN[p]?.computed;
  return p !== "all" && Array.isArray(c) ? c.flatMap(leaves) : [p];
};

const names = Object.keys(properties);
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
const chrome = await page.evaluate((names) => {
  const d = document.createElement("div");
  const out = Object.fromEntries(
    names.map((p) => {
      d.style.cssText = "";
      d.style.setProperty(p, "initial");
      return [p, [...d.style]];
    }),
  );
  // `all` lists nothing in an inline style: it is every longhand but direction and unicode-bidi (css-cascade-5 §3.2)
  out.all = [...getComputedStyle(document.body)].filter(
    (l) => !l.startsWith("--") && l !== "direction" && l !== "unicode-bidi",
  );
  return out;
}, names);
await browser.close();

const out = {};
for (const p of names) {
  const set = chrome[p].length ? chrome[p] : [...new Set(leaves(p))];
  if (set.length !== 1 || set[0] !== p) out[p] = [...new Set(set)].sort();
}
writeFileSync(
  `${import.meta.dirname}/../src/longhands.ts`,
  `// Generated by scripts/longhands.mjs (bun run longhands): the longhands of each shorthand, as Chrome expands it.\n// A property that is not here is a longhand.\nexport const longhands: Record<string, readonly string[] | undefined> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`${Object.keys(out).length} shorthands; all: ${out.all?.length}`);
