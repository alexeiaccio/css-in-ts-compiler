// node diff.ts — grammar-generated values against three judges: the twin, Chrome, the types.
// Fails on real bugs (twin rejects a generated value; types and twin disagree). Chrome disagreements are
// reported, not failed: they are the catalogue of where mdn-data, the engine and the twin part ways.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

import * as fc from "fast-check";
import { chromium } from "playwright-core";

import { arbFor } from "./gen.ts";
import { properties } from "../src/mdn.ts";
import { matches, valid } from "./sync.ts";

const SEED = Number(process.env.SEED ?? 42);
const N = Number(process.env.N ?? 20);
const props: Record<string, string> = properties;
const names = Object.keys(props);
let failed = false;

// 1. twin accepts everything the grammar generates (fast-check shrinks the counterexample)
const selfFail: string[] = [];
const skipped: string[] = [];
for (const p of names) {
  const a = arbFor(p);
  if (!a) {
    skipped.push(p);
    continue;
  }
  const r = fc.check(
    fc.property(a, (v) => matches(props[p]!, v)),
    { seed: SEED, numRuns: 200 },
  );
  if (r.failed) selfFail.push(`${p}: ${JSON.stringify(r.counterexample?.[0])}`);
}
console.log(`\n# twin vs generator: ${names.length - skipped.length} properties, 200 values each`);
if (skipped.length) console.log(`not generatable: ${skipped.join(", ")}`);
selfFail.forEach((l) => console.log(`REJECTED ${l}`));
failed ||= selfFail.length > 0;

// 2. samples and mutants. Mutants may still be valid; Chrome is the judge for them.
type Case = { p: string; v: string; kind: "gen" | "mut"; twin: boolean };
const cases: Case[] = [];
for (const p of names) {
  const a = arbFor(p);
  if (!a) continue;
  fc.sample(a, { seed: SEED, numRuns: N }).forEach((v, i) => {
    cases.push({ p, v, kind: "gen", twin: matches(props[p]!, v) });
    const t = v.split(" ");
    const j = i % t.length;
    const mut = [
      [...t.slice(0, j), ...t.slice(j + 1)], // drop a token
      [...t.slice(0, j + 1), ...t.slice(j)], // duplicate a token
      t.length > 1 ? [...t.slice(1), t[0]] : [...t, t[0]], // rotate
    ][i % 3]!.join(" ");
    if (mut && mut !== v) cases.push({ p, v: mut, kind: "mut", twin: matches(props[p]!, mut) });
  });
}

// 3. Chrome (installed browser, no download): CSS.supports is the engine's own parser
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
const chrome: boolean[] = await page.evaluate(
  (cs) => cs.map(([p, v]) => CSS.supports(p, v)),
  cases.map((c) => [c.p, c.v] as [string, string]),
);
const version = browser.version();
await browser.close();

const groups = new Map<string, Case[]>();
cases.forEach((c, i) => {
  if (c.twin === chrome[i]) return;
  const key = `${c.kind} ${c.twin ? "twin accepts, chrome rejects" : "twin rejects, chrome accepts"}`;
  groups.set(key, [...(groups.get(key) ?? []), c]);
});
const agree = cases.filter((c, i) => c.twin === chrome[i]).length;
console.log(`\n# twin vs Chrome ${version}: ${agree}/${cases.length} agree`);
for (const [key, cs] of groups) {
  const byProp = new Map<string, string[]>();
  cs.forEach((c) => byProp.set(c.p, [...(byProp.get(c.p) ?? []), c.v]));
  console.log(`\n## ${key}: ${cs.length}`);
  for (const [p, vs] of byProp)
    console.log(
      `  ${p} (${vs.length}): ${vs
        .slice(0, 3)
        .map((v) => JSON.stringify(v))
        .join("  ")}`,
    );
}

// 4. types on a sample: each case is `const cN: Matches<...> = <twin verdict>`, so every error line is a disagreement
const sample = names.flatMap((p) => [
  ...cases.filter((c) => c.p === p && c.kind === "gen").slice(0, 4),
  ...cases.filter((c) => c.p === p && c.kind === "mut").slice(0, 4),
]);
mkdirSync("out", { recursive: true });
writeFileSync(
  "out/diff.gen.ts",
  `// generated by diff.ts\nimport type { Matches } from "../src/css";\nimport type { properties } from "../src/mdn";\ntype P = typeof properties;\n` +
    sample
      .map(
        (c, i) =>
          `export const c${i}: Matches<P[${JSON.stringify(c.p)}], ${JSON.stringify(c.v)}> = ${c.twin};`,
      )
      .join("\n") +
    "\n",
);
let out = "";
try {
  execFileSync(
    "../../node_modules/.bin/tsgo",
    ["--ignoreConfig", "--strict", "--noEmit", "--skipLibCheck", "out/diff.gen.ts"],
    { encoding: "utf8" },
  );
} catch (e) {
  out = (e as { stdout: string }).stdout;
}
// The types strip numeric ranges by design: a row that only the twin's range check rejects is no disagreement.
const rangeOnly = (c: Case) => {
  if (c.twin) return false;
  try {
    valid(c.p, c.v);
    return false;
  } catch (e) {
    return ((e as { expected?: string[] }).expected ?? []).some((x) => / \[[^\]]*\]>$/.test(x));
  }
};
// Nor do they check what follows `from` in a relative colour, or the conditions of an if(): balanced tokens there.
const opaqueOnly = (c: Case) =>
  !c.twin && /\b(rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(\s*from\b|\bif\(/.test(c.v);
const typeFail = [...out.matchAll(/diff\.gen\.ts\((\d+),/g)]
  .map((m) => sample[Number(m[1]) - 5]!)
  .filter((c) => !rangeOnly(c) && !opaqueOnly(c));
console.log(`\n# types vs twin (tsgo): ${sample.length - typeFail.length}/${sample.length} agree`);
typeFail.forEach((c) =>
  console.log(`  ${c.p}: ${JSON.stringify(c.v)} twin=${c.twin} types=${!c.twin}`),
);
failed ||= typeFail.length > 0;

process.exit(failed ? 1 : 0);
