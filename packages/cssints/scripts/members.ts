// Regenerates src/members.ts: the names a user can import from "cssints" with { type: "cssints" } (every property
// as camelCase, plus the short set), and the chain methods of flex() and grid(). Types only; the values exist
// after the plugin rewrote the import. Run: node scripts/members.ts (bun run members)
import { writeFileSync } from "node:fs";

import { chainNames, PROPS } from "../src/lib.ts";

// Not properties of `css`: the builders macro.ts defines itself.
const OWN = new Set(["cn", "flex", "grid", "cv"]);
const names = Object.keys(PROPS).filter((n) => !OWN.has(n)).sort();
const union = (ctx: string) => chainNames(ctx).map((n) => JSON.stringify(n)).join(" | ");

writeFileSync(
  `${import.meta.dirname}/../src/members.ts`,
  `// Generated by scripts/members.ts from PROPS and CONTEXTS in lib.ts. Do not edit.
import type { Member } from "./types.ts";

${names.map((n) => `export declare const ${n}: Member;`).join("\n")}

export type FlexMethods = ${union("flex")};
export type GridMethods = ${union("grid")};
`,
);
console.log(`members.ts: ${names.length} properties`);
