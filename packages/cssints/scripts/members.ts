// Regenerates src/members.ts: the names a user can import from "cssints" with { type: "cssints" } (every property
// as camelCase, plus the short set, and a wrapper for every pseudo-class), and the chain methods of flex() and grid().
// Types only; the values exist
// after the plugin rewrote the import. Run: node scripts/members.ts (bun run members)
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

import { properties } from "@cssints/css-grammar/mdn";
import { get as bcd } from "@cssints/css-grammar/support";

import { chainNames, CONTEXTS, PROPS, PSEUDOS } from "../src/lib.ts";

// Not properties of `css`: the builders macro.ts defines itself.
const OWN = new Set([
  "cn",
  "firstThatWorks",
  "keyframes",
  "flex",
  "grid",
  "cv",
  "media",
  "container",
  "supports",
  "attr",
  "group",
  "within",
  "global",
  "layers",
  "token",
  "style",
  "createTokens",
  "createGlobalTheme",
  "check",
]);
const names = Object.keys(PROPS)
  .filter((n) => !OWN.has(n))
  .sort();
const pseudos = Object.keys(PSEUDOS).sort();
const clash = pseudos.filter((n) => n in PROPS || OWN.has(n));
if (clash.length)
  throw new Error(`pseudo-class wrappers clash with other members: ${clash.join(", ")}`);
// JSDoc, one line per member: the grammar, the first version of each target browser that supports it without a prefix
// or a flag (BCD; "no" when none does, "?" when BCD does not know), and the MDN page.
const need = createRequire(import.meta.url);
type Pages = Record<string, { mdn_url?: string } | undefined>;
const propPages = need("mdn-data/css/properties.json") as Pages;
const selectorPages = need("mdn-data/css/selectors.json") as Pages;
const TARGETS = [
  ["chrome", "Chrome"],
  ["edge", "Edge"],
  ["firefox", "Firefox"],
  ["safari", "Safari"],
  ["safari_ios", "iOS"],
  ["chrome_android", "Android"],
] as const;
const doc = (head: string, key: string, url = "") => {
  const c = bcd(key)?.__compat;
  const row = c
    ? TARGETS.map(([b, label]) => {
        const s = c.support[b];
        const ok =
          s &&
          [s]
            .flat()
            .find((x) => !x.prefix && !x.alternative_name && !x.flags && !x.version_removed);
        const v = ok?.version_added;
        return `${label} ${s === undefined || v === null ? "?" : typeof v === "string" && v !== "preview" ? v : "no"}`;
      }).join(", ")
    : "";
  const page = url || c?.mdn_url;
  return `/** ${[head, row, page && `[MDN](${page})`].filter(Boolean).join(". ")} */`;
};
const propDoc = (p: string) =>
  doc(
    `\`${properties[p as keyof typeof properties].replaceAll("~w", "")}\``, // `<grid-line~w>` is the webref twin of mdn-data's type
    `css.properties.${p}`,
    propPages[p]?.mdn_url,
  );
const pseudoDoc = (n: string) => {
  const { text } = PSEUDOS[n]!;
  return doc("", `css.selectors.${text.slice(1)}`, selectorPages[text]?.mdn_url);
};
// method -> property, per context
const methods = (ctx: string) =>
  `{\n${chainNames(ctx)
    .map(
      (n, i) => `  ${propDoc(CONTEXTS[ctx]![i]!)}\n  ${n}: ${JSON.stringify(CONTEXTS[ctx]![i])};`,
    )
    .join("\n")}\n}`;

// flex and grid: no argument is the context (Chain), parts are the shorthand property
const layout = (ctx: string, M: string) =>
  `${propDoc(ctx)}\nexport declare const ${ctx}: Layout<${JSON.stringify(ctx)}, ${M}Methods>;`;

writeFileSync(
  `${import.meta.dirname}/../src/members.ts`,
  `// Generated by scripts/members.ts from PROPS, CONTEXTS and PSEUDOS in lib.ts. Do not edit.
import type { Layout, Prop, StateWrap } from "./types.ts";

${names.map((n) => `${propDoc(PROPS[n]!)}\nexport declare const ${n}: Prop<${JSON.stringify(PROPS[n])}>;`).join("\n")}

${pseudos.map((n) => `${pseudoDoc(n)}\nexport declare const ${n}: StateWrap;`).join("\n")}

export type FlexMethods = ${methods("flex")};
export type GridMethods = ${methods("grid")};

${layout("flex", "Flex")}
${layout("grid", "Grid")}
`,
);
console.log(`members.ts: ${names.length} properties, ${pseudos.length} pseudo-classes`);
