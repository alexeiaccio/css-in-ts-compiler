// Writes src/tokens.d.json.ts, the type of src/tokens.json with its literal values (a JSON import widens them to string),
// so a token shows its value on hover (t.space.sm: Token<"length", true, "8px">). `--check` fails when it is stale.
import { readFileSync, writeFileSync } from "node:fs";

const json = new URL("../src/tokens.json", import.meta.url);
const out = new URL("../src/tokens.d.json.ts", import.meta.url);
const text = `// Generated by scripts/tokens-types.mjs from tokens.json: do not edit.\ndeclare const tokens: ${JSON.stringify(JSON.parse(readFileSync(json, "utf8")), null, 2)};\nexport default tokens;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/tokens.d.json.ts is stale: run node scripts/tokens-types.mjs");
    process.exit(1);
  }
} else writeFileSync(out, text);
